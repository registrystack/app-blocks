// Writes documents/pdf-resources.ts, the PDF reader's one import per CMap,
// standard font and licence file that pdfjs-dist ships. Each import names the
// file from the package, never by a path relative to the block, so the
// bundler finds it wherever the registry installs the reader, and a file the
// package no longer ships fails the build. Run it again after changing the
// pdfjs-dist version:
//
//   pnpm run pdf-resources     (from project/blocks/)

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const licences = [
  "LICENSE",
  "cmaps/LICENSE",
  "standard_fonts/LICENSE_FOXIT",
  "standard_fonts/LICENSE_LIBERATION",
];

/** The files the reader bundles, relative to the pdfjs-dist package folder. */
export function pdfResourceFiles(pdfjs) {
  const listed = (directory, pattern) =>
    readdirSync(join(pdfjs, directory))
      .filter((name) => pattern.test(name))
      .sort()
      .map((name) => `${directory}/${name}`);
  for (const licence of licences)
    if (!existsSync(join(pdfjs, licence)))
      throw new Error(`pdfjs-dist ships no ${licence}`);
  return [
    ...listed("cmaps", /\.bcmap$/),
    ...listed("standard_fonts", /\.(?:pfb|ttf)$/),
    ...licences,
  ];
}

/** The module text: one asset import per file, and a map keyed by that path. */
export function renderPdfResources(version, files) {
  const key = (file) =>
    /^[A-Za-z_$][\w$]*$/.test(file) ? file : JSON.stringify(file);
  return [
    `// PDF.js's CMaps, standard fonts and licences from pdfjs-dist ${version}, one`,
    "// asset import each. Generated by the App Kit's scripts/write-pdf-resources.mjs;",
    "// regenerate it for another pdfjs-dist version rather than edit it.",
    "",
    ...files.map(
      (file, index) =>
        `import resource${index} from "pdfjs-dist/${file}?url&no-inline";`,
    ),
    "",
    "/** Bundled asset URLs, keyed by their path in the pdfjs-dist package. */",
    "export const pdfResources: Readonly<Record<string, string>> = {",
    ...files.map((file, index) => `  ${key(file)}: resource${index},`),
    "};",
    "",
  ].join("\n");
}

/** The pdfjs-dist version installed at a package folder. */
export function pdfjsVersion(pdfjs) {
  return JSON.parse(readFileSync(join(pdfjs, "package.json"), "utf8")).version;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const blocks = fileURLToPath(new URL("..", import.meta.url));
  const pdfjs = join(blocks, "node_modules", "pdfjs-dist");
  const files = pdfResourceFiles(pdfjs);
  const out = join(blocks, "documents", "pdf-resources.ts");
  writeFileSync(out, renderPdfResources(pdfjsVersion(pdfjs), files));
  console.log(`Wrote ${out}: ${files.length} resources`);
}
